async function sightline(page, actorIndex) {
  return page.evaluate(async i=>{
    await new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)));
    const T=await import("three"),a=__JEJAKA__.actors[i],c=__JEJAKA__.camera;
    a.root.updateMatrixWorld(true);c.updateMatrixWorld(true);
    const h=a.root.getObjectByName("head"),v=new T.Vector3();
    if(h)h.getWorldPosition(v);else a.root.getWorldPosition(v).add(new T.Vector3(0,1.4,0));
    v.y+=.1;const n=v.clone().project(c),d=document.getElementById("dialogue").getBoundingClientRect();
    const x=(n.x+1)*innerWidth/2,y=(1-n.y)*innerHeight/2;
    return {chapter:__JEJAKA__.state.chapter,actor:i,headWorld:v.toArray(),headScreen:[x,y],headNDC:n.toArray(),dialogue:{x:d.x,y:d.y,right:d.right,bottom:d.bottom},insideView:Math.abs(n.x)<1&&Math.abs(n.y)<1&&n.z<1,coveredByCaption:x>=d.x&&x<=d.right&&y>=d.y&&y<=d.bottom};
  },actorIndex);
}
async function layout(page, width, height, chapter) {
  await page.setViewportSize({width,height});
  await page.evaluate(i => {
    // Layout staging requires an unanswered encounter, not its saved/hidden UI.
    __JEJAKA__.state.entries=[];
    __JEJAKA__.state.choices={};
    __JEJAKA__.goto(i);
  }, chapter);
  await page.evaluate(() => document.fonts.ready);
  await page.waitForTimeout(500);
  assert(await page.locator(".choice").first().isVisible(),"Layout test did not stage unanswered choice");
  const v = await page.evaluate(() => {
    const r = el => {const b=el.getBoundingClientRect();return {x:b.x,y:b.y,width:b.width,height:b.height,bottom:b.bottom,right:b.right};};
    const a = r(document.querySelector(".choice")), d=r(document.getElementById("dialogue"));
    const top = r(document.querySelector(".hud-top"));
    return {choice:a,dialogue:d,header:top,overlap:Math.max(0,Math.min(a.bottom,d.bottom)-Math.max(a.y,d.y)),overflow:document.documentElement.scrollWidth>innerWidth+1};
  });
  assert.equal(v.overlap,0,`Caption overlaps choice at ${width}x${height}, chapter ${chapter}: ${JSON.stringify(v)}`);
  assert(v.dialogue.y >= v.header.bottom - 1,`Dialogue under header ${width}x${height}: ${JSON.stringify(v)}`);
  assert(v.choice.bottom <= height+1,`Choice clipped at ${width}x${height}`);
  assert.equal(v.overflow,false,`Horizontal overflow at ${width}x${height}`);
  return {width,height,chapter,...v};
}
