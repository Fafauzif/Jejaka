const server = http.createServer((req, res) => {
  try {
    let p = path.resolve(root, "." + decodeURIComponent(req.url.split("?")[0]));
    if (p !== root && !p.startsWith(root + path.sep)) throw Error("Outside root");
    if (fs.statSync(p).isDirectory()) p = path.join(p, "index.html");
    const d = fs.readFileSync(p);
    res.setHeader("Content-Type", ({html:"text/html",js:"text/javascript",css:"text/css",mp3:"audio/mpeg",gz:"application/gzip",woff:"font/woff"})[p.split(".").pop()] || "application/octet-stream");
    res.setHeader("Content-Length", d.length);
    res.end(d);
  } catch { res.writeHead(404); res.end(); }
});
